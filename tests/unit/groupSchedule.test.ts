// Which group-class lessons may be rebuilt when the class is edited.
import { test } from "node:test";
import assert from "node:assert/strict";
import { isRegeneratableScheduleLesson } from "../../src/lib/groupSchedule.ts";

const TODAY = "2026-10-14"; // Wednesday
const weekly = {
  frequency: "weekly", days_of_week: ["monday", "wednesday"],
  start_date: "2026-10-01", end_date: "2026-11-30", start_time: "16:00:00",
};
const row = (date: string, extra: Record<string, any> = {}) => ({
  lesson_date: date, start_time: "16:00:00", is_recurring: true, billing_status: "unbilled", ...extra,
});
const check = (r: any, schedule: any = weekly) => isRegeneratableScheduleLesson(r, schedule, TODAY);

test("upcoming unbilled occurrences generated by the schedule are rebuilt", () => {
  assert.equal(check(row("2026-10-14")), true, "today counts");
  assert.equal(check(row("2026-10-19")), true);
  assert.equal(check(row("2026-11-30")), true, "end date inclusive");
});

test("past, billed and paid lessons are never touched", () => {
  assert.equal(check(row("2026-10-12")), false, "past");
  assert.equal(check(row("2026-10-19", { billing_status: "billed" })), false);
  assert.equal(check(row("2026-10-19", { billing_status: "paid" })), false);
});

test("sessions attached from the Lessons page are kept", () => {
  assert.equal(check(row("2026-10-23", { is_recurring: false, start_time: "17:00:00" })), false, "Friday one-off");
  assert.equal(check(row("2026-10-19", { is_recurring: false })), false, "one-off on a class weekday");
});

test("an occurrence moved to another time is kept", () => {
  assert.equal(check(row("2026-10-21", { start_time: "18:00:00" })), false);
  assert.equal(check(row("2026-10-21", { start_time: "16:00" })), true, "HH:MM and HH:MM:SS compare equal");
});

test("rows outside the schedule's weekdays or date range are kept", () => {
  assert.equal(check(row("2026-10-15")), false, "Thursday");
  assert.equal(check(row("2026-12-02")), false, "after end date");
});

test("biweekly classes match by weekday, regardless of which week the cycle started", () => {
  const biweekly = { ...weekly, frequency: "biweekly" };
  assert.equal(check(row("2026-10-19"), biweekly), true);
  assert.equal(check(row("2026-10-26"), biweekly), true);
});

test("one-time classes only rebuild their single date", () => {
  const once = { frequency: "once", days_of_week: [], start_date: "2026-10-20", end_date: null, start_time: "16:00:00" };
  assert.equal(check(row("2026-10-20", { is_recurring: false }), once), true);
  assert.equal(check(row("2026-10-21", { is_recurring: false }), once), false);
});
